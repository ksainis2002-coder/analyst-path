/* =========================================================================
   data.js: datasets as JS objects (spec §6)
   -------------------------------------------------------------------------
   The engine reads a flat cell map ({ A1: "OrderID", F2: 3, … }). Humans
   (and the §6 generator) think in tables. toCells() turns a list of
   positioned tables into one cell map, so a sheet can hold an orders table
   in A:F and a lookup table in H:J side by side, exactly like v1.

   AEGEAN is the course dataset (spec §6), generated by
   content/_generators/aegean.mjs. One sheet, four tables side by side:

     A:H  Orders    OrderID · Date · ProductID · Region · Rep · Channel · Quantity · Discount
     J:N  Products  ProductID · ProductName · Category · UnitCost · ListPrice
     P:T  Reps      RepID · RepName · Region · HireDate · Target
     V:X  Tiers     MinQty · Band · Discount   (sorted, for approximate match)

   Dates are Excel date serials (numbers), exactly as Excel stores them, so
   COUNT sees them and they sort correctly. `formats` tells the sheet to SHOW
   them as dates, and discounts as percentages. The engine only ever sees the
   raw numbers.
   AEGEAN_MESSY is the same order log with seeded defects (Level 3 cleaning);
   `defects` documents each one so the grader can verify fixes.

   V1_SAMPLE is the v1 app's 24-order dataset. It's kept for the engine and
   UI tests and the console demo page; course content uses AEGEAN.
   ========================================================================= */
import AEGEAN_RAW from "./data/aegean.generated.js";

/** Column letters ↔ 1-based index. */
export function colToIndex(letters) { let n = 0; for (const ch of letters) n = n * 26 + (ch.charCodeAt(0) - 64); return n; }
export function indexToCol(n) { let s = ""; while (n > 0) { s = String.fromCharCode(65 + ((n - 1) % 26)) + s; n = Math.floor((n - 1) / 26); } return s; }

/**
 * Build a cell map from positioned tables.
 * @param {{origin: string, header?: string[], rows: any[][]}[]} tables
 *   origin: top-left cell of the table (the header row if there is one), e.g. "H1".
 * @returns {Object<string, string|number|boolean>} frozen cell map. Empty cells are simply absent.
 */
export function toCells(tables) {
  const cells = {};
  for (const t of tables) {
    const m = /^([A-Z]+)(\d+)$/.exec(t.origin);
    if (!m) throw new Error(`Bad table origin "${t.origin}"`);
    const c0 = colToIndex(m[1]); let r = Number(m[2]);
    const put = (row, rr) => row.forEach((v, i) => {
      if (v === null || v === undefined || v === "") return;
      const key = indexToCol(c0 + i) + rr;
      if (key in cells) throw new Error(`Tables overlap at ${key}`);
      cells[key] = v;
    });
    if (t.header) put(t.header, r++);
    t.rows.forEach(row => put(row, r++));
  }
  return Object.freeze(cells);
}

