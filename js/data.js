/* ---------- display formats (shared by the sheet and the console) ---------- */
/** Excel date serial → "YYYY-MM-DD". */
export function serialToISO(n) {
  const d = new Date(Date.UTC(1899, 11, 30) + Math.round(n) * 86400000);
  return d.toISOString().slice(0, 10);
}
/** Show a raw value the way its column is formatted ("date", "percent"), like Excel's number formats. */
export function formatAs(v, format) {
  if (typeof v !== "number" || !format) return null;
  if (format === "date") return serialToISO(v);
  if (format === "percent") return `${Math.round(v * 10000) / 100}%`;
  return null;
}
/** The format of a cell, from its column letter. */
export function formatOf(dataset, key) {
  const m = /^([A-Z]+)\d+$/.exec(key || ""); return m ? dataset?.formats?.[m[1]] || null : null;
}

